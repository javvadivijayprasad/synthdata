// Exporters: CSV files, SQL insert script, SQLite .db (via sql.js WASM),
// PostgreSQL load script, and MySQL/MariaDB load script.
import fs from 'node:fs';
import path from 'node:path';
import { topoOrder, splitTopLevel } from './schema.js';

export function toCsv(data, outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  for (const [tname, rows] of Object.entries(data)) {
    if (!rows.length) continue;
    const cols = Object.keys(rows[0]);
    const esc = (v) => {
      if (v == null) return '';
      const s = String(v);
      return /[",\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
    };
    const lines = [cols.join(','), ...rows.map(r => cols.map(c => esc(r[c])).join(','))];
    fs.writeFileSync(path.join(outDir, `${tname}.csv`), lines.join('\n'), 'utf-8');
  }
}

const sqlVal = (v) => v == null ? 'NULL'
  : typeof v === 'number' ? String(v)
  : "'" + String(v).replace(/'/g, "''") + "'";

export function insertStatements(data) {
  const out = [];
  for (const [tname, rows] of Object.entries(data)) {
    for (const r of rows) {
      // meta columns (e.g. _violation from the negative profile) become comments,
      // so the INSERT itself stays runnable against the real schema
      const cols = Object.keys(r).filter(k => !k.startsWith('_'));
      const note = r._violation ? `  -- violation: ${r._violation}` : '';
      out.push(`INSERT INTO ${tname} (${cols.join(',')}) VALUES (${cols.map(c => sqlVal(r[c])).join(',')});${note}`);
    }
  }
  return out;
}

export function toSqlFile(data, filePath) {
  fs.writeFileSync(filePath, insertStatements(data).join('\n') + '\n', 'utf-8');
}

// ---- PostgreSQL export ----
// Emits one psql-loadable script: DDL + batched INSERTs in FK dependency
// order, wrapped in a single transaction. Handles what SQLite didn't need:
//   - OVERRIDING SYSTEM VALUE for GENERATED ALWAYS AS IDENTITY columns
//   - TRUE/FALSE literals for BOOLEAN columns (PG rejects 0/1 in inserts)
//   - setval() so identity sequences continue after the explicit IDs
const PG_BATCH = 500;

export function ddlToPostgres(ddl) {
  return ddl
    .replace(/\bAUTOINCREMENT\b/gi, '')       // SQLite-ism
    .replace(/\bDATETIME\b/gi, 'TIMESTAMP');  // SQLite/MySQL-ism
}

const pgVal = (v, isBool) => {
  if (v == null) return 'NULL';
  if (isBool) return (v === true || v === 1 || v === '1' || v === 'TRUE') ? 'TRUE' : 'FALSE';
  return typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'";
};

export function toPostgresSql(ddl, tables, data, filePath, seed) {
  const lines = [
    '-- Generated by @vijaypjavvadi/synthdata' + (seed != null ? ` (seed=${seed})` : ''),
    `-- Load with: psql -d your_db -f ${path.basename(filePath)}`,
    '', 'BEGIN;', '', ddlToPostgres(ddl).trim(), '',
    '-- data (foreign-key dependency order)',
  ];
  const setvals = [];
  for (const tname of topoOrder(tables)) {
    const rows = data[tname];
    if (!rows || !rows.length) continue;
    const cols = Object.keys(rows[0]);
    const tcols = tables[tname].columns;
    const boolCols = new Set(tcols.filter(c => c.dtype.includes('BOOL')).map(c => c.name));
    const ov = tcols.some(c => c.identity && cols.includes(c.name)) ? ' OVERRIDING SYSTEM VALUE' : '';
    for (const c of tcols) {
      if (c.identity && cols.includes(c.name)) {
        setvals.push(`SELECT setval(pg_get_serial_sequence('${tname}', '${c.name}'), ` +
                     `COALESCE((SELECT MAX(${c.name}) FROM ${tname}), 1));`);
      }
    }
    lines.push(`\n-- ${tname}: ${rows.length} rows`);
    for (let i = 0; i < rows.length; i += PG_BATCH) {
      const chunk = rows.slice(i, i + PG_BATCH);
      lines.push(`INSERT INTO ${tname} (${cols.join(', ')})${ov} VALUES`);
      lines.push(chunk.map(r =>
        '  (' + cols.map(c => pgVal(r[c], boolCols.has(c))).join(', ') + ')').join(',\n') + ';');
    }
  }
  if (setvals.length) lines.push('\n-- resume identity sequences after explicit IDs', ...setvals);
  lines.push('', 'COMMIT;', '');
  fs.writeFileSync(filePath, lines.join('\n'), 'utf-8');
}

// ---- MySQL / MariaDB export ----
// Emits one mysql-loadable script: DDL + batched INSERTs in FK dependency order.
// Differences from the PostgreSQL target:
//   - GENERATED ALWAYS AS IDENTITY -> AUTO_INCREMENT (explicit IDs are allowed and
//     the counter resumes after MAX(id) automatically — no setval needed)
//   - TIMESTAMP -> DATETIME (no 2038 limit, no implicit ON UPDATE behaviour)
//   - backtick-quoted identifiers, backslash-escaped string literals
//   - FOREIGN_KEY_CHECKS off during load (DDL order may not be FK order)
//   - DDL statements implicitly commit in MySQL, so only the INSERTs run in a transaction
const MYSQL_BATCH = 500;

// MySQL parses but silently IGNORES inline `col TYPE REFERENCES t(c)` — no constraint
// is created. Hoist every inline REFERENCES into a table-level FOREIGN KEY so the
// loaded database actually enforces referential integrity.
const INLINE_REF = /\s*REFERENCES\s+["`]?(\w+)["`]?\s*(?:\(\s*["`]?(\w+)["`]?\s*\))?((?:\s+ON\s+(?:DELETE|UPDATE)\s+(?:CASCADE|SET\s+NULL|SET\s+DEFAULT|RESTRICT|NO\s+ACTION))*)/i;

function hoistForeignKeys(ddl) {
  const clean = ddl.replace(/--[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '');
  const re = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?["`]?\w+["`]?\s*\(/gi;
  let out = '', last = 0, m;
  while ((m = re.exec(clean)) !== null) {
    let depth = 1, i = re.lastIndex, inStr = false;
    while (i < clean.length && depth > 0) {
      const ch = clean[i];
      if (ch === "'") inStr = !inStr;
      if (!inStr) { if (ch === '(') depth++; if (ch === ')') depth--; }
      i++;
    }
    const parts = splitTopLevel(clean.slice(re.lastIndex, i - 1));
    const fks = [];
    const kept = parts.map(part => {
      if (/^(PRIMARY\s+KEY|UNIQUE|FOREIGN\s+KEY|CHECK|CONSTRAINT)\b/i.test(part)) return part;
      const cm = /^["`]?(\w+)["`]?\s/.exec(part);
      const ref = cm && INLINE_REF.exec(part);
      if (!ref) return part;
      fks.push(`FOREIGN KEY (${cm[1]}) REFERENCES ${ref[1]}${ref[2] ? `(${ref[2]})` : ''}${(ref[3] || '').replace(/\s+/g, ' ')}`);
      return part.replace(INLINE_REF, '');
    });
    out += clean.slice(last, re.lastIndex) + '\n    ' + [...kept, ...fks].join(',\n    ') + '\n)';
    last = i;
  }
  return out + clean.slice(last);
}

export function ddlToMysql(ddl) {
  return hoistForeignKeys(ddl)
    .replace(/\b(BIGINT|INT|INTEGER|SMALLINT)\s+GENERATED\s+(?:ALWAYS|BY\s+DEFAULT)\s+AS\s+IDENTITY/gi, '$1 AUTO_INCREMENT')
    .replace(/\bAUTOINCREMENT\b/gi, 'AUTO_INCREMENT')
    .replace(/\bTIMESTAMP\b/gi, 'DATETIME');
}

const myIdent = (n) => '`' + String(n).replace(/`/g, '``') + '`';

const myVal = (v, isBool) => {
  if (v == null) return 'NULL';
  if (isBool) return (v === true || v === 1 || v === '1' || v === 'TRUE') ? 'TRUE' : 'FALSE';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
  return "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "''").replace(/\0/g, '\\0') + "'";
};

export function toMysqlSql(ddl, tables, data, filePath, seed) {
  const lines = [
    '-- Generated by @vijaypjavvadi/synthdata' + (seed != null ? ` (seed=${seed})` : ''),
    '-- Load with: mysql your_db < this_file.sql',
    '', 'SET NAMES utf8mb4;', 'SET FOREIGN_KEY_CHECKS = 0;', '',
    ddlToMysql(ddl).trim(), '',
    '-- data (foreign-key dependency order)', 'START TRANSACTION;',
  ];
  for (const tname of topoOrder(tables)) {
    const rows = data[tname];
    if (!rows || !rows.length) continue;
    // meta columns (e.g. _violation from the negative profile) are not real columns
    const cols = Object.keys(rows[0]).filter(k => !k.startsWith('_'));
    const boolCols = new Set(tables[tname].columns.filter(c => c.dtype.includes('BOOL')).map(c => c.name));
    lines.push(`\n-- ${tname}: ${rows.length} rows`);
    for (let i = 0; i < rows.length; i += MYSQL_BATCH) {
      const chunk = rows.slice(i, i + MYSQL_BATCH);
      lines.push(`INSERT INTO ${myIdent(tname)} (${cols.map(myIdent).join(', ')}) VALUES`);
      lines.push(chunk.map(r =>
        '  (' + cols.map(c => myVal(r[c], boolCols.has(c))).join(', ') + ')').join(',\n') + ';');
    }
  }
  lines.push('', 'COMMIT;', 'SET FOREIGN_KEY_CHECKS = 1;', '');
  fs.writeFileSync(filePath, lines.join('\n'), 'utf-8');
}

// Transpile our supported DDL subset to SQLite-compatible DDL.
export function ddlToSqlite(ddl) {
  return ddl
    .replace(/(BIGINT|INT|INTEGER)\s+GENERATED\s+ALWAYS\s+AS\s+IDENTITY/gi, 'INTEGER')
    .replace(/\bBOOLEAN\b/gi, 'INTEGER')
    .replace(/\bTIMESTAMP\b/gi, 'TEXT')
    .replace(/DEFAULT\s+CURRENT_TIMESTAMP/gi, "DEFAULT (datetime('now'))");
}

export async function toSqliteDb(ddl, data, dbPath) {
  const { default: initSqlJs } = await import('sql.js');
  const SQL = await initSqlJs();
  const db = new SQL.Database();
  db.run('PRAGMA foreign_keys = ON;');
  db.run(ddlToSqlite(ddl));
  for (const [tname, rows] of Object.entries(data)) {
    if (!rows.length) continue;
    const cols = Object.keys(rows[0]);
    const stmt = db.prepare(`INSERT INTO ${tname} (${cols.join(',')}) VALUES (${cols.map(() => '?').join(',')})`);
    db.run('BEGIN');
    for (const r of rows) stmt.run(cols.map(c => r[c] === undefined ? null : r[c]));
    db.run('COMMIT');
    stmt.free();
  }
  const violations = db.exec('PRAGMA foreign_key_check');
  fs.writeFileSync(dbPath, Buffer.from(db.export()));
  db.close();
  if (violations.length) throw new Error(`FK check failed: ${violations[0].values.length} violations`);
}
